import { describe, expect, it } from 'vitest'
import { presentChecks, presentExplanation } from './explanationPresentation'

const ai = 'AI-selected explanation using recorded information; wording is generated by PHAROS templates.'
const fallback = 'Deterministic explanation: AI is unavailable or its response could not be used.'
const review = 'Unreviewed: these recorded details have not completed human review.'
const skill = 'One of your saved skills matches a tag recorded for this opportunity. Consider whether its content adds something to what you already know.'
const time = "You saved 5 learning hours per week. Compare this with the provider's workload; the record does not establish that it fits your schedule."
const limited = 'The available profile and recorded topics do not establish a direct match. Compare the description with your learning goals before deciding.'
const checks = 'Next checks: use the source link on this page to confirm the current application or enrollment window, eligibility, learning costs versus certification fees, deadlines and workload. Unknown details remain unknown. This explanation does not confirm eligibility, availability, fees or deadlines.'

describe('explanation presentation trust boundaries', () => {
  it.each([[ai, 'ai'], [fallback, 'fallback'], ['Deterministic explanation: this is a fictional demo, not a real opportunity.', 'demo']] as const)('recognizes only the explicit mode: %s', (modeText, mode) => {
    const result = presentExplanation([modeText, review, skill, time, checks].join('\n\n'))
    expect(result.mode).toBe(mode)
    expect(result.modeText).toBe(modeText)
    expect(result.blocks.map(block => block.kind)).toEqual(['review', 'skill', 'time', 'checks'])
    expect([result.modeText, ...result.blocks.map(block => block.text)].join('\n\n')).toBe([modeText, review, skill, time, checks].join('\n\n'))
  })

  it.each(['AI-selected explanation', 'AI-selected explanation failed; fallback used.', 'An AI-selected explanation is not available.', 'constructor', `${ai}\nAdditional qualification.`])('does not infer AI selection from unfamiliar wording: %s', text => {
    const result = presentExplanation(text)
    expect(result.mode).toBe('unknown')
    expect(result.modeText).toBeNull()
    expect(result.blocks).toEqual([{ kind: 'text', text }])
  })

  it('never invents skill or time insights when evidence is insufficient', () => {
    const result = presentExplanation([fallback, review, limited, checks].join('\r\n\r\n'))
    expect(result.blocks.map(block => block.kind)).toEqual(['review', 'limited', 'checks'])
    expect(result.blocks.find(block => block.kind === 'limited')?.text).toBe(limited)
  })

  it('keeps unfamiliar statements and warnings intact and in order', () => {
    const paragraphs = ['Ollama unavailable. No selection was made.', 'Your saved skill does not match this record.', 'Additional source warning.\nKeep this qualification.', 'Next checks: contact the provider.']
    const result = presentExplanation(paragraphs.join('\n\n'))
    expect(result.mode).toBe('unknown')
    expect(result.blocks.map(block => block.text)).toEqual(paragraphs)
    expect(result.blocks.map(block => block.kind)).toEqual(['text', 'text', 'text', 'checks'])
    expect(presentChecks(paragraphs[3])).toBeNull()
  })

  it('retains zero and fractional weekly hours without inferring schedule fit', () => {
    for (const hours of ['0', '2.5']) {
      const text = time.replace('5 learning', `${hours} learning`)
      expect(presentExplanation(text).blocks).toEqual([{ kind: 'time', text }])
    }
  })

  it('recognizes the recorded interest statement without changing its eligibility caveat', () => {
    const text = 'Your saved interest in data science matches a topic recorded for this opportunity. This may make it worth exploring; it does not establish eligibility.'
    expect(presentExplanation(text).blocks).toEqual([{ kind: 'interest', text }])
  })

  it('preserves every checklist item and limitation from the response', () => {
    const result = presentChecks(checks)!
    expect(result.items).toHaveLength(5)
    expect(`${result.intro}${result.items.slice(0, -1).join(', ')} and ${result.items.at(-1)}. ${result.limitation}`).toBe(checks)
    expect(presentChecks(checks.replace('Unknown details remain unknown. ', ''))).toBeNull()
  })
})
